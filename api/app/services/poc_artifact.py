"""Reproducible PoC artifact generator.

Per backlog-413: when ``exploit_validator`` confirms an exploit, produce a
standalone Python script that a human pentester can run via:

    python poc.py --target http://victim:8080

The script replays the exact captured request chain, asserts the same
response markers the validator used, and exits 0 on reproduction, 2 on
missing markers, 1 on network error. It depends only on ``httpx``
(installed in any AegisPT host) so no AegisPT internals leak into the
artifact.

Per ``poc_replayable_by_human``: the script is portable. It does not
reference AegisPT services, scope-allowlists, or governance plane —
just the captured HTTP chain.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from typing import Any

SCRIPT_TEMPLATE = '''#!/usr/bin/env python3
"""Auto-generated PoC for finding: {title!r}.
Auto-generated by AegisPT backlog-413 — do NOT hand-edit.
SHA-256 of source recipe: {recipe_sha}.
"""
from __future__ import annotations

import argparse
import sys

try:
    import httpx
except ImportError:  # pragma: no cover
    print("PoC requires httpx (pip install httpx)", file=sys.stderr)
    sys.exit(3)


EXPECTED_MARKERS = {expected_markers!r}
STEPS = {steps!r}


def main() -> int:
    parser = argparse.ArgumentParser(description={title!r})
    parser.add_argument("--target", required=True, help="Base URL (e.g. http://victim:8080)")
    parser.add_argument("--timeout", type=float, default=10.0, help="Per-step timeout seconds")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    observed: list[str] = []
    with httpx.Client(timeout=args.timeout, follow_redirects=False, verify=False) as client:
        for i, step in enumerate(STEPS, start=1):
            method = str(step.get("method") or "GET").upper()
            url = step.get("url") or args.target
            if isinstance(url, str) and url.startswith("/"):
                url = args.target.rstrip("/") + url
            headers = {{
                str(k): str(v)
                for k, v in (step.get("headers") or {{}}).items()
                if str(k).lower() != "host"
            }}
            body = step.get("body")
            if args.verbose:
                print(f"[{{i}}] {{method}} {{url}}")
            try:
                if method in {{"POST", "PUT", "PATCH"}} and body is not None:
                    if isinstance(body, (dict, list)):
                        resp = client.request(method, url, headers=headers, json=body)
                    else:
                        resp = client.request(method, url, headers=headers, content=str(body))
                else:
                    resp = client.request(method, url, headers=headers)
            except httpx.HTTPError as exc:
                print(f"network error on step {{i}}: {{exc}}", file=sys.stderr)
                return 1
            for marker in EXPECTED_MARKERS:
                if marker and marker in (resp.text or ""):
                    observed.append(marker)

    missing = [m for m in EXPECTED_MARKERS if m not in observed]
    if missing:
        print("missing markers: " + repr(missing), file=sys.stderr)
        return 2
    print("reproduced: " + repr(EXPECTED_MARKERS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


@dataclass
class PoCArtifact:
    """Result of :func:`build_executable_poc`."""

    script_text: str
    recipe_sha: str
    title: str
    expected_markers: list[str]


def build_executable_poc(finding: Any, captured_evidence: dict[str, Any] | None = None) -> PoCArtifact:
    """Generate a standalone PoC script for a verified finding.

    ``finding`` is duck-typed: ``.title`` + ``.replay_recipe_json`` (or
    ``.replay_recipe``). ``captured_evidence`` lets callers override the
    finding's recipe with a separately-captured artifact.
    """
    recipe = (
        captured_evidence
        or getattr(finding, "replay_recipe_json", None)
        or getattr(finding, "replay_recipe", None)
        or {}
    )
    if not isinstance(recipe, dict):
        recipe = {}
    steps_raw = recipe.get("steps")
    steps = [s for s in (steps_raw or []) if isinstance(s, dict)]
    expected_markers_raw = recipe.get("expected_markers") or []
    expected_markers = [str(m) for m in expected_markers_raw if isinstance(m, str) and m]
    title = str(getattr(finding, "title", "") or "AegisPT PoC")
    recipe_sha = hashlib.sha256(
        json.dumps(recipe, sort_keys=True, default=str).encode("utf-8"),
    ).hexdigest()
    script_text = SCRIPT_TEMPLATE.format(
        title=title,
        recipe_sha=recipe_sha,
        expected_markers=expected_markers,
        steps=steps,
    )
    return PoCArtifact(
        script_text=script_text,
        recipe_sha=recipe_sha,
        title=title,
        expected_markers=expected_markers,
    )


__all__ = ["PoCArtifact", "build_executable_poc"]
