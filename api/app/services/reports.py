def run_attack_narrative_context(run: Run, context: dict[str, object] | None = None) -> dict[str, object]:
    context = context or report_context(run)
    findings = [finding for finding in context.get("findings", []) if isinstance(finding, Finding)]
    tasks = [task for task in context.get("tasks", []) if isinstance(task, Task)]
    inventory_summary = context.get("inventory_summary", {})
    if not isinstance(inventory_summary, dict):
        inventory_summary = {}

    attack_summary = build_attack_path_summary_for_loaded_run(run)
    attack_core = attack_summary.get("summary", {}) if isinstance(attack_summary, dict) else {}
    candidate_paths = [
        path for path in attack_summary.get("candidate_paths", []) if isinstance(path, dict)
    ] if isinstance(attack_summary, dict) else []
    choke_points = [
        point for point in attack_summary.get("choke_points", []) if isinstance(point, dict)
    ] if isinstance(attack_summary, dict) else []
    chains = _stored_chain_summaries(run)
    source_evidence_refs = _run_narrative_evidence_refs(findings, candidate_paths, chains)
    source_categories = _run_narrative_source_categories(
        inventory_summary=inventory_summary,
        candidate_paths=candidate_paths,
        chains=chains,
        source_evidence_refs=source_evidence_refs,
    )

    has_stored_material = bool(
        findings
        or tasks
        or inventory_summary
        or candidate_paths
        or choke_points
        or chains
        or source_evidence_refs
    )
    limitations: list[str] = [
        "Narrative text is advisory and requires operator review before customer use.",
        "The narrative is limited to stored run records and does not assert that exploitation was proven.",
    ]
    if run.status not in RUN_ATTACK_NARRATIVE_ELIGIBLE_STATUSES:
        status = "unavailable"
        available = False
        limitations.insert(0, "Narrative unavailable until the run reaches completed or completed_with_errors.")
    elif not has_stored_material:
        status = "limited"
        available = True
        limitations.insert(0, "Sparse completed run data: no findings, inventory, attack paths, chains, or evidence refs were recorded.")
    elif not findings and not candidate_paths and not chains:
        status = "limited"
        available = True
        limitations.insert(0, "Limited completed-run narrative: reconnaissance or task data exists, but no confirmed findings, attack paths, or chains were recorded.")
    else:
        status = "ready"
        available = True

