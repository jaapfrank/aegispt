def _run_narrative_path_summaries(candidate_paths: list[dict[str, object]]) -> list[dict[str, object]]:
    sorted_paths = sorted(
        candidate_paths,
        key=lambda path: (
            SEVERITY_ORDER.get(str(path.get("severity") or "unknown").lower(), SEVERITY_ORDER["unknown"]),
            -float(path.get("confidence") or 0.0),
            str(path.get("finding_title") or ""),
        ),
    )
    summaries: list[dict[str, object]] = []
    for path in sorted_paths[:5]:
        labels = [
            str(label)
            for label in list(path.get("labels") or [])
            if str(label or "").strip()
        ]
        summaries.append(
            {
                "id": str(path.get("id") or ""),
                "finding_id": str(path.get("finding_id") or ""),
                "finding_title": str(path.get("finding_title") or "Untitled finding"),
                "severity": str(path.get("severity") or "unknown"),
                "target_id": str(path.get("target_id") or "not recorded"),
                "confidence": path.get("confidence") or 0.0,
                "labels": labels,
                "path": " -> ".join(labels) if labels else "No path labels recorded.",
                "evidence_refs": [
                    str(ref)
                    for ref in list(path.get("evidence_refs") or [])
                    if str(ref or "").strip()
                ],
                "explanation": str(path.get("explanation") or "No path explanation recorded."),
            }
        )
    return summaries


def _build_run_narrative_sections(
    *,
    run: Run,
    status: str,
    available: bool,
    findings: list[Finding],
    top_findings: list[Finding],
    tasks: list[Task],
    inventory_summary: dict[str, object],
    attack_core: dict[str, object],
    path_summaries: list[dict[str, object]],
    chains: list[dict[str, object]],
    source_categories: list[str],
    source_evidence_refs: list[str],
    limitations: list[str],
) -> list[dict[str, object]]:
    if not available:
        return [
            _run_narrative_section(
                section_id="availability",
                title="Narrative Availability",
                body=(
                    f"AI-assisted/advisory run attack narrative is unavailable for run status {run.status}. "
                    "Complete the run first, then regenerate this review layer from stored evidence."
                ),
                source_categories=source_categories,
                source_evidence_refs=source_evidence_refs,
            )
        ]

    host_count = inventory_summary.get("host_count", 0)
    service_count = inventory_summary.get("service_count", 0)
    endpoint_count = inventory_summary.get("endpoint_count", 0)
    recon_body = (
        f"AI-assisted/advisory narrative: reconnaissance recorded {host_count} hosts, "
        f"{service_count} services, and {endpoint_count} endpoints for this run. "
        f"The narrative also references {len(tasks)} task records and remains limited to stored execution output."
        if inventory_summary
        else (
            "AI-assisted/advisory narrative: no discovery-confirmed inventory snapshot is linked to this run. "
            f"The narrative can only reference {len(tasks)} task records and stored findings."
        )
    )

    if path_summaries:
        top_path = path_summaries[0]
        path_body = (
            "AI-assisted/advisory narrative: the existing attack-path summary produced "
            f"{attack_core.get('candidate_path_count', len(path_summaries))} candidate paths and "
            f"{attack_core.get('choke_point_count', 0)} choke points. Top reviewed path: "
            f"{top_path['path']} ({top_path['severity']} finding, confidence {top_path['confidence']})."
        )
    else:
        path_body = (
            "AI-assisted/advisory narrative: no evidence-backed attack paths were derived from the stored "
            "inventory and finding data for this run."
        )

    if chains:
        first_chain = chains[0]
        chain_body = (
            f"AI-assisted/advisory narrative: {len(chains)} stored vulnerability-chain detection records are available. "
            f"Highest-confidence chain: {first_chain['title']} ({first_chain['status']}, confidence "
            f"{first_chain['confidence_score']}). {first_chain['combined_impact']}"
        )
    else:
        chain_body = (
            "AI-assisted/advisory narrative: no stored vulnerability-chain detections are attached to this run. "
            "No chained-impact claim should be made without later operator-reviewed evidence."
        )

    if top_findings:
        finding_lines = "; ".join(
            f"{finding.severity} {finding.title} on {finding.target_id}"
            for finding in top_findings[:3]
        )
        findings_body = (
            f"AI-assisted/advisory narrative: priority operator review should focus on {finding_lines}. "
            "Remediation priority remains advisory and must be verified against the canonical findings."
        )
    else:
        findings_body = (
            "AI-assisted/advisory narrative: no confirmed findings were recorded, so this section cannot "
            "claim exploited weaknesses or remediation urgency."
        )

    limitation_body = " ".join(limitations)
    if status == "limited":
        limitation_body = f"Limited narrative status: {limitation_body}"

    return [
        _run_narrative_section(
            section_id="reconnaissance",
            title="Reconnaissance Narrative",
            body=recon_body,
            source_categories=source_categories,
            source_evidence_refs=source_evidence_refs,
        ),
        _run_narrative_section(
            section_id="attack_paths",
            title="Attack Path Narrative",
            body=path_body,
            source_categories=source_categories,
            source_evidence_refs=source_evidence_refs,
        ),
        _run_narrative_section(
            section_id="chain_detections",
            title="Chain Detection Narrative",
            body=chain_body,
            source_categories=source_categories,
            source_evidence_refs=source_evidence_refs,
        ),
        _run_narrative_section(
            section_id="critical_findings",
            title="Critical Findings and Remediation Narrative",
            body=findings_body,
            source_categories=source_categories,
            source_evidence_refs=source_evidence_refs,
        ),
        _run_narrative_section(
            section_id="review_boundary",
            title="Operator Review Boundary",
            body=limitation_body,
            source_categories=source_categories,
            source_evidence_refs=source_evidence_refs,
        ),
    ]


