def compliance_gap_advisor_context(context: dict[str, object], variant: str) -> dict[str, object]:
    if variant == "soc2":
        compliance = soc2_report_package_context(context)
        group_label = "SOC 2 Control"
    else:
        compliance = compliance_framework_package_context(context, variant)
        group_label = str(compliance.get("group_label") or "Control")

    definition = COMPLIANCE_GAP_ADVISOR_DEFINITIONS[variant]
    coverage_rows = compliance["coverage_rows"]
    assert isinstance(coverage_rows, list)

    covered = [
        {
            "control_id": str(row["control_id"]),
            "title": str(row["title"]),
            "finding_count": int(row["finding_count"]),
            "basis": str(row["basis"]),
            "status": "Covered by evidence-backed finding",
        }
        for row in coverage_rows
        if isinstance(row, dict) and int(row.get("finding_count", 0)) > 0
    ]
    not_tested_technical = [
        {
            "control_id": str(row["control_id"]),
            "title": str(row["title"]),
            "reason": (
                "No evidence-backed finding or confirmed-clean control evidence was recorded for this "
                "testable technical control in this run."
            ),
            "next_step": "Run or attach relevant technical evidence, then regenerate the compliance report.",
        }
        for row in coverage_rows
        if isinstance(row, dict) and int(row.get("finding_count", 0)) == 0
    ]
    not_tested_process = [
        {
            "control_id": "",
            "title": str(item["control"]),
            "reason": (
                f"{item['reason']} This control requires organisational process review, "
                "not a technical scan."
            ),
            "next_step": str(item["next_step"]),
        }
        for item in definition["not_tested"]
        if isinstance(item, dict)
    ]

    total_testable = int(compliance["total_mapped_controls"])
    covered_count = int(compliance["mapped_control_count"])
    coverage_percentage = round((covered_count / total_testable) * 100) if total_testable else 0
    package = str(definition["package"])

    return {
        "package": package,
        "reference": compliance.get("reference"),
        "group_label": group_label,
        "technical_scope": definition["technical_scope"],
        "covered": covered,
        "not_tested": not_tested_technical + not_tested_process,
        "requires_human_auditor": [
            {
                "framework": item["framework"],
                "requirement": item["requirement"],
                "next_step": item["next_step"],
            }
            for item in HUMAN_AUDITOR_REQUIREMENTS
        ],
        "covered_count": covered_count,
        "total_testable_controls": total_testable,
        "coverage_percentage": coverage_percentage,
        "coverage_statement": (
            f"This assessment covered {covered_count} of {total_testable} testable {package} "
            "technical controls represented in AegisPT's report-time mapping "
            f"({coverage_percentage}%). This is not full framework compliance coverage."
        ),
        "next_steps": list(definition["next_steps"]),
    }


def _render_compliance_gap_advisor_markdown(advisor: dict[str, object]) -> list[str]:
    covered = advisor["covered"]
    not_tested = advisor["not_tested"]
    auditor_requirements = advisor["requires_human_auditor"]
    next_steps = advisor["next_steps"]
    assert isinstance(covered, list)
    assert isinstance(not_tested, list)
    assert isinstance(auditor_requirements, list)
    assert isinstance(next_steps, list)

    lines = [
        "## Compliance Gap Advisor",
        "",
        f"- Framework: {advisor['package']}",
        f"- Technical Coverage: {advisor['coverage_percentage']}%",
        f"- Coverage Basis: {advisor['technical_scope']}",
        f"- Coverage Statement: {advisor['coverage_statement']}",
        "",
        "### Covered by This Assessment",
        "",
    ]
    if covered:
        for item in covered:
            assert isinstance(item, dict)
            lines.append(
                f"- Covered: {item['control_id']} - {item['title']} "
                f"({item['finding_count']} evidence-backed finding(s)); {item['basis']}"
            )
    else:
        lines.append(
            "- No testable compliance controls had evidence-backed findings or confirmed-clean evidence in this run."
        )

    lines.extend(["", "### Not Tested in This Run", ""])
    for item in not_tested:
        assert isinstance(item, dict)
        label = (
            f"{item['control_id']} - {item['title']}"
            if item.get("control_id")
            else str(item["title"])
        )
        lines.extend(
            [
                f"- Not tested: {label}",
                f"  - Why: {item['reason']}",
                f"  - Next step: {item['next_step']}",
            ]
        )

    lines.extend(["", "### Requires Human Auditor", ""])
    for item in auditor_requirements:
        assert isinstance(item, dict)
        lines.extend(
            [
                f"- {item['framework']}: {item['requirement']}",
                f"  - Next step: {item['next_step']}",
            ]
        )

    lines.extend(["", "### Coverage Percentage", "", f"- {advisor['coverage_statement']}", ""])
    lines.extend(["### Framework-Specific Next Steps", ""])
    for step in next_steps:
        lines.append(f"- {step}")
    lines.append("")
    return lines


