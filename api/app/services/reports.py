def _normalize_soc2_token(value: object) -> str:
    return str(value or "").strip().lower().replace("-", "_").replace(" ", "_")


def _soc2_mapping_for_finding(finding: Finding) -> tuple[dict[str, object], str] | None:
    control_family = _normalize_soc2_token(finding.control_family)
    methodology_tags = {
        _normalize_soc2_token(tag)
        for tag in (finding.methodology_tags or [])
        if isinstance(tag, str) and tag.strip()
    }
    wstg_id = str(finding.wstg_id or "").upper()
    asvs_reference = str(finding.asvs_reference or "").upper()

    for mapping in SOC2_CONTROL_MAPPINGS:
        control_families = set(mapping.get("control_families", set()))
        if control_family and control_family in control_families:
            return mapping, f"control_family={finding.control_family}"

        mapped_tags = set(mapping.get("methodology_tags", set()))
        tag_matches = sorted(methodology_tags.intersection(mapped_tags))
        if tag_matches:
            return mapping, f"methodology_tags={', '.join(tag_matches)}"

        for prefix in mapping.get("wstg_prefixes", ()):
            if isinstance(prefix, str) and wstg_id.startswith(prefix):
                return mapping, f"wstg_id={finding.wstg_id}"

        for prefix in mapping.get("asvs_prefixes", ()):
            if isinstance(prefix, str) and asvs_reference.startswith(prefix):
                return mapping, f"asvs_reference={finding.asvs_reference}"

    return None


