def _assurance_finding_state(finding: Finding) -> str:
    if finding.status == "resolved":
        return "resolved in the finding record; retain linked evidence and retest proof before relying on closure"
    if finding.status == "accepted_risk":
        return "accepted residual risk"
    if finding.status == "false_positive":
        return "marked false positive in the finding record"
    if finding.status in ASSURANCE_UNRESOLVED_STATUSES:
        return "unresolved or not yet verified"
    return f"recorded status: {finding.status}"


def _finding_remediation_state(finding: Finding) -> str:
    remediation = getattr(finding, "remediation", None)
    if remediation is None:
        return "not recorded"
    return str(remediation.state or "not recorded")


