def _deduplicated_finding_rows(findings: list[Finding]) -> list[dict[str, object]]:
    grouped: dict[str, list[Finding]] = {}
    for finding in findings:
        key = str(finding.title or "Untitled finding").strip().lower()
        grouped.setdefault(key, []).append(finding)

    rows: list[dict[str, object]] = []
    for group in grouped.values():
        ordered = sorted(group, key=lambda finding: (_severity_rank(finding.severity), finding.target_id, finding.id.hex))
        representative = ordered[0]
        targets = sorted({str(finding.target_id or "Not recorded") for finding in ordered})
        evidence_refs = sorted({str(finding.evidence_ref or "") for finding in ordered if str(finding.evidence_ref or "").strip()})
        rows.append(
            {
                "title": representative.title,
                "severity": representative.severity,
                "status": representative.status,
                "priority": remediation_priority_for_finding(representative),
                "count": len(ordered),
                "targets": targets,
                "evidence_refs": evidence_refs,
                "representative": representative,
                "summary": representative.summary or "",
            }
        )
    return sorted(rows, key=lambda row: (_severity_rank(str(row["severity"])), str(row["title"]).lower()))


