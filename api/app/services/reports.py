def _nfir_signal_text(*parts: object) -> str:
    return " ".join(str(part or "").lower() for part in parts)


def _nfir_phase_for_text(text: str, *, default: str = "vulnerability-analysis") -> str:
    lowered = text.lower()
    if any(token in lowered for token in ("bloodhound", "sharphound", "ldap", "kerberoast", "asrep", "password-spray", "credential")):
        return "post-exploitation"
    if any(token in lowered for token in ("metasploit", "impacket", "psexec", "wmiexec", "secretsdump", "dcsync", "exploit")):
        return "exploitation"
    if any(token in lowered for token in ("nuclei", "zap", "vulnerability", "validation", "smb", "enum", "audit")):
        return "vulnerability-analysis"
    if any(token in lowered for token in ("httpx", "easm", "nmap", "discovery", "inventory", "recon", "fingerprint")):
        return "intelligence-gathering"
    if any(token in lowered for token in ("report", "retest", "remediation", "sla", "false-positive", "false_positive")):
        return "risk-analysis-remediation"
    return default


def _nfir_phase_for_task(task: Task) -> str:
    profile_name = task.params_json.get("profile_name") if isinstance(task.params_json, dict) else None
    mode = task.params_json.get("mode") if isinstance(task.params_json, dict) else None
    return _nfir_phase_for_text(
        _nfir_signal_text(task.tool, task.target_id, profile_name, mode),
        default="intelligence-gathering",
    )


def _nfir_phase_for_finding(finding: Finding) -> str:
    if str(finding.ptes_phase or "").lower() == "reporting":
        return "reporting-retest"
    if str(finding.status or "").lower() in {"resolved", "verified_resolved"}:
        return "risk-analysis-remediation"
    return _nfir_phase_for_text(
        _nfir_signal_text(
            finding.title,
            finding.target_id,
            finding.evidence_ref,
            finding.finding_origin,
            finding.control_family,
            finding.ptes_phase,
            finding.nist_phase,
            " ".join(finding.methodology_tags or []),
        ),
        default="vulnerability-analysis",
    )


def _cvss_display(finding: Finding) -> str:
    if finding.cvss_score is None:
        return "N/A"
    return f"{finding.cvss_score:g}" + (f" ({finding.cvss_vector})" if finding.cvss_vector else "")


def _finding_age_days(finding: Finding, now: datetime) -> int:
    created = finding.created_at
    if created.tzinfo is None:
        created = created.replace(tzinfo=UTC)
    return max(0, int((now - created.astimezone(UTC)).total_seconds() // 86400))


def _finding_retest_status(finding: Finding) -> str:
    records = list(finding.validation_records or [])
    if records:
        latest = sorted(records, key=lambda record: (record.created_at, record.id.hex), reverse=True)[0]
        return str(latest.status or "validation recorded").replace("_", " ")
    remediation = finding.remediation
    if remediation is not None:
        return f"remediation {remediation.state}".replace("_", " ")
    if str(finding.status or "").lower() in {"resolved", "verified_resolved"}:
        return "verified resolved in finding status"
    return "not requested"


def nfir_report_context(run: Run, context: dict[str, object]) -> dict[str, object]:
    findings = [finding for finding in context.get("findings", []) if isinstance(finding, Finding)]
    tasks = [task for task in context.get("tasks", []) if isinstance(task, Task)]
    engagement = run.engagement
    now = datetime.now(UTC)
    phase_records = {
        phase["key"]: {
            **phase,
            "tasks": [],
            "findings": [],
            "status": "skipped",
            "skip_reason": "No task or finding evidence mapped to this NFIR phase for this run.",
        }
        for phase in NFIR_PHASES
    }

    for task in tasks:
        phase_records[_nfir_phase_for_task(task)]["tasks"].append(task)
    for finding in findings:
        phase_records[_nfir_phase_for_finding(finding)]["findings"].append(finding)

    authorization_recorded = bool(
        engagement is not None and (engagement.roe_ref or engagement.authorization_confirmed_at)
    )
    preparation = phase_records["preparation-authorization"]
    if authorization_recorded or context.get("approvals"):
        preparation["status"] = "executed"
        preparation["skip_reason"] = ""
    else:
        preparation["skip_reason"] = NFIR_AUTHORIZATION_WARNING

    risk_phase = phase_records["risk-analysis-remediation"]
    if findings:
        risk_phase["status"] = "executed"
        risk_phase["skip_reason"] = ""
    else:
        risk_phase["skip_reason"] = "No findings were recorded, so there is no finding-backed risk or remediation queue."

    reporting = phase_records["reporting-retest"]
    reporting["status"] = "executed"
    reporting["skip_reason"] = ""

    for record in phase_records.values():
        if record["tasks"] or record["findings"]:
            record["status"] = "executed"
            record["skip_reason"] = ""

    open_statuses = {"open", "triaged", "in_progress", "reopened", "accepted_risk"}
    resolved_statuses = {"resolved", "verified_resolved", "false_positive"}
    open_findings = [finding for finding in findings if str(finding.status or "").lower() in open_statuses]
    resolved_findings = [finding for finding in findings if str(finding.status or "").lower() in resolved_statuses]
    return {
        "reference": NFIR_REPORT_REFERENCE,
        "boundary": NFIR_REPORT_BOUNDARY,
        "authorization": {
            "roe_ref": engagement.roe_ref if engagement is not None and engagement.roe_ref else None,
            "confirmed_at": engagement.authorization_confirmed_at if engagement is not None else None,
            "confirmed_by": engagement.authorization_confirmed_by if engagement is not None else None,
            "recorded": authorization_recorded,
            "warning": "" if authorization_recorded else NFIR_AUTHORIZATION_WARNING,
        },
        "phases": [phase_records[phase["key"]] for phase in NFIR_PHASES],
        "open_findings": [
            {
                "finding": finding,
                "age_days": _finding_age_days(finding, now),
                "retest_status": _finding_retest_status(finding),
            }
            for finding in open_findings
        ],
        "resolved_findings": [
            {
                "finding": finding,
                "age_days": _finding_age_days(finding, now),
                "retest_status": _finding_retest_status(finding),
            }
            for finding in resolved_findings
        ],
    }


