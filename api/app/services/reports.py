def _run_narrative_evidence_refs(
    findings: list[Finding],
    candidate_paths: list[dict[str, object]],
    chains: list[dict[str, object]],
) -> list[str]:
    refs = {
        str(finding.evidence_ref).strip()
        for finding in findings
        if str(finding.evidence_ref or "").strip()
    }
    for path in candidate_paths:
        refs.update(
            str(ref).strip()
            for ref in list(path.get("evidence_refs") or [])
            if str(ref or "").strip()
        )
    for chain in chains:
        refs.update(
            str(ref).strip()
            for ref in list(chain.get("evidence_refs") or [])
            if str(ref or "").strip()
        )
    return sorted(refs)


