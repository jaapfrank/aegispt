def _humanize_value(value: object) -> str:
    if value is None:
        return "Not recorded"
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return value.strip() or "Not recorded"
    if isinstance(value, list):
        items = [_humanize_value(item) for item in value if _humanize_value(item) != "Not recorded"]
        return ", ".join(items) if items else "Not recorded"
    if isinstance(value, dict):
        parts = []
        for key in sorted(value):
            rendered = _humanize_value(value[key])
            if rendered != "Not recorded":
                parts.append(f"{_humanize_key(str(key))}: {rendered}")
        return "; ".join(parts) if parts else "Not recorded"
    return str(value)


