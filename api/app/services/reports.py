def _severity_rank(severity: str | None) -> int:
    return SEVERITY_ORDER.get(str(severity or "unknown").lower(), SEVERITY_ORDER["unknown"])


def _risk_score(findings: list[Finding]) -> float:
    weights = {"critical": 10.0, "high": 7.0, "medium": 4.0, "low": 1.5, "info": 0.0, "unknown": 0.0}
    score = sum(weights.get(str(finding.severity or "unknown").lower(), 0.0) for finding in findings)
    return round(min(10.0, score / 2.0), 1)


def _risk_level(score: float) -> str:
    if score >= 8.0:
        return "HIGH"
    if score >= 4.0:
        return "MEDIUM"
    if score > 0:
        return "LOW"
    return "INFORMATIONAL"


def _risk_bar(score: float) -> str:
    filled = max(0, min(10, int(round(score))))
    return "█" * filled + "░" * (10 - filled)


