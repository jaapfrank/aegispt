def _signals_match(text: str, keywords: tuple[str, ...]) -> bool:
    return any(keyword in text for keyword in keywords)


def _run_has_wireless_evidence(run: Run) -> bool:
    snapshot = effective_inventory_snapshot_for_run(run)
    normalized_inventory = (
        snapshot.normalized_inventory_json
        if snapshot is not None
        and isinstance(getattr(snapshot, "normalized_inventory_json", None), dict)
        else {}
    )
    return bool(
        normalized_inventory.get("wireless_access_points")
        or normalized_inventory.get("wireless_networks")
    )


def report_sections_for_run(run: Run) -> list[str]:
    task_signals = " ".join(_task_signal_text(task) for task in list(run.tasks or []))
    run_signal = _run_signal_text(run)
    sections = list(ALWAYS_REPORT_SECTIONS)

    for rule in SURFACE_COVERAGE_RULES:
        if rule["key"] == "wifi_wireless" and not _run_has_wireless_evidence(run):
            continue
        keywords = tuple(str(keyword) for keyword in rule["keywords"])
        if _signals_match(task_signals, keywords) or _signals_match(run_signal, keywords):
            for section in rule["sections"]:
                section_key = str(section)
                if section_key not in sections:
                    sections.append(section_key)

    return sections


def build_test_coverage_block(run: Run, tasks: list[Task]) -> dict[str, object]:
    executed_tasks = [task for task in tasks if task.status in EXECUTED_TASK_STATUSES]
    executed_signal = " ".join(_task_signal_text(task) for task in executed_tasks)
    tested: list[dict[str, object]] = []
    not_tested: list[dict[str, object]] = []

    for rule in SURFACE_COVERAGE_RULES:
        keywords = tuple(str(keyword) for keyword in rule["keywords"])
        matching_tasks = [task for task in executed_tasks if _signals_match(_task_signal_text(task), keywords)]
        entry = {
            "key": rule["key"],
            "label": rule["label"],
            "task_count": len(matching_tasks),
            "tools": sorted({task.tool for task in matching_tasks}),
            "sections": list(rule["sections"]),
        }
        if matching_tasks or _signals_match(executed_signal, keywords):
            tested.append(entry)
        else:
            not_tested.append(
                {
                    **entry,
                    "reason": "No executed task in this run exercised this surface.",
                }
            )

    return {
        "tested_surfaces": tested,
        "not_tested_surfaces": not_tested,
        "executed_task_count": len(executed_tasks),
        "total_task_count": len(tasks),
        "tools": sorted({task.tool for task in executed_tasks}),
        "section_keys": report_sections_for_run(run),
    }


