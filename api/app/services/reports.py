def _iot_security_summary_lines(context: dict[str, object]) -> list[str]:
    inventory_summary = context.get("inventory_summary", {})
    inventory_snapshot = context.get("inventory_snapshot")
    normalized_inventory = (
        inventory_snapshot.normalized_inventory_json
        if inventory_snapshot is not None
        and isinstance(getattr(inventory_snapshot, "normalized_inventory_json", None), dict)
        else {}
    )
    hosts = [
        host
        for host in normalized_inventory.get("hosts", [])
        if isinstance(host, dict)
    ]
    device_types = sorted(
        {
            str(host.get("device_type") or "").strip()
            for host in hosts
            if str(host.get("device_type") or "").strip()
        }
    )
    device_lines = [
        f"- {host.get('host')}: {host.get('device_type')}"
        for host in hosts
        if str(host.get("device_type") or "").strip()
    ][:12]
    findings = [finding for finding in context.get("findings", []) if isinstance(finding, Finding)]
    unauthenticated = [
        finding
        for finding in findings
        if any(
            token in " ".join([finding.title, finding.summary or ""]).lower()
            for token in ("unauth", "anonymous", "no auth", "open management")
        )
    ]
    default_creds = [
        finding
        for finding in findings
        if any(
            token in " ".join([finding.title, finding.summary or ""]).lower()
            for token in ("default credential", "accepted default", "default password")
        )
    ]
    segmentation = [
        finding
        for finding in findings
        if any(
            token in " ".join([finding.title, finding.summary or ""]).lower()
            for token in ("segmentation", "vlan", "cross-segment", "ipv6")
        )
    ]
    lines = [
        "- Device Types: " + (", ".join(device_types) if device_types else "None recorded"),
        f"- IoT Device Type Count: {inventory_summary.get('device_type_count', len(device_types)) if isinstance(inventory_summary, dict) else len(device_types)}",
        f"- Unauthenticated Service Findings: {len(unauthenticated)}",
        f"- Default Credential Findings: {len(default_creds)}",
        f"- Segmentation / IPv6 Findings: {len(segmentation)}",
        "",
        "#### Device Inventory",
        "",
    ]
    lines.extend(device_lines or ["- No typed IoT devices are recorded in the linked inventory snapshot."])
    lines.append("")
    return lines


